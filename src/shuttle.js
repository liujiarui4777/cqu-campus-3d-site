function toMin(t) {
  const [h, m] = String(t).split(':').map(Number);
  return h * 60 + m;
}

export function fmtMin(min) {
  const h = Math.floor(min / 60) % 24;
  const m = min % 60;
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}`;
}

/** 返回今天从该站出发的班次（含已过/未过标记） */
export function todaySchedule(stopIdx = 0, dir = 'outbound') {
  const table = SHUTTLE[dir];
  const now = new Date();
  const nowMin = now.getHours() * 60 + now.getMinutes();
  return table.times.map((row) => {
    const t = row[stopIdx];
    const m = toMin(t);
    return { time: t, min: m, passed: m < nowMin, inMin: m - nowMin };
  });
}

export function nextBus(stopIdx = 0, dir = 'outbound') {
  const list = todaySchedule(stopIdx, dir).filter((x) => !x.passed);
  return list.length ? list[0] : null;
}
